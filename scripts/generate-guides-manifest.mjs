// Task 9 (performance): generates src/data/guides/manifest.js - a single
// lightweight file listing every guide's display metadata (slug, title,
// summary, icon, category, gameSlug) plus the relative path to its own
// module.
//
// WHY THIS EXISTS
// ---------------
// src/data/guides/index.js statically imports ~1000+ individual guide
// modules (one per game, ~12 MB of JS in total). Anything that imports
// index.js therefore pulls the entire set:
//   - guides.html  (the listing) - needed only title/slug/summary/icon
//   - guide.html   (ONE guide)   - needed only that one guide's content
//   - every game page (game-guide-notice) - needed only "does a guide
//     exist for this slug?"
// On a static host that is 1000+ module requests + parse on page load, for
// pages that need a tiny fraction of it - the main cause of the Guides
// page sitting visibly empty for seconds.
//
// The manifest is ~one small file. The listing and the notice read it
// directly; guide.html reads it for metadata and then dynamically
// imports() only the single module it actually needs.
//
// This repo has no bundler/build step - modules are served raw - so the
// manifest is generated and committed. test/guidesManifest.test.js
// re-runs this logic and fails if the committed file is stale, so it can
// never silently drift from index.js. Re-run after adding/removing a
// guide:  node scripts/generate-guides-manifest.mjs

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const GUIDES_DIR = path.join(__dirname, "..", "src", "data", "guides");
const INDEX_PATH = path.join(GUIDES_DIR, "index.js");
const MANIFEST_PATH = path.join(GUIDES_DIR, "manifest.js");

// Parses index.js into two ordered lists of { module } (relative path
// within src/data/guides, e.g. "games/hades.js") - one for APP_GUIDES,
// one for GAME_GUIDES - preserving the exact order the arrays declare, so
// the manifest renders guides in the same order the page always has.
export async function buildManifestData() {

    const source = await readFile(INDEX_PATH, "utf8");

    // import { GUIDE as <name> } from "./<path>";
    const importRe = /import\s*\{\s*GUIDE\s+as\s+(\w+)\s*\}\s*from\s*"\.\/([^"]+)"/g;
    const nameToModule = new Map();

    for (const match of source.matchAll(importRe)) {

        nameToModule.set(match[1], match[2]);

    }

    const orderedNames = section => {

        const block = source.match(new RegExp(`export const ${section} = \\[([\\s\\S]*?)\\];`));

        if (!block) {

            throw new Error(`Could not find "export const ${section}" array in index.js`);

        }

        return block[1]
            .split(",")
            .map(entry => entry.trim())
            .filter(Boolean);

    };

    const summarize = async names => {

        const out = [];

        for (const name of names) {

            const moduleRel = nameToModule.get(name);

            if (!moduleRel) {

                throw new Error(`No import found for guide "${name}" referenced in an export array`);

            }

            const mod = await import(pathToFileURL(path.join(GUIDES_DIR, moduleRel)).href);
            const guide = mod.GUIDE;

            if (!guide?.slug) {

                throw new Error(`Guide module ${moduleRel} has no GUIDE.slug`);

            }

            out.push({
                slug: guide.slug,
                title: guide.title,
                summary: guide.summary,
                icon: guide.icon,
                category: guide.category,
                gameSlug: guide.gameSlug ?? null,
                module: moduleRel
            });

        }

        return out;

    };

    return {
        app: await summarize(orderedNames("APP_GUIDES")),
        game: await summarize(orderedNames("GAME_GUIDES"))
    };

}

export function renderManifest({ app, game }) {

    const stringify = list => list
        .map(entry => "    " + JSON.stringify(entry))
        .join(",\n");

    return `// AUTO-GENERATED by scripts/generate-guides-manifest.mjs - do not edit by hand.
// Lightweight display metadata for every guide (see the generator's header
// for why this exists). Kept in sync with src/data/guides/index.js by
// test/guidesManifest.test.js. Regenerate after adding/removing a guide:
//   node scripts/generate-guides-manifest.mjs

export const APP_GUIDE_SUMMARIES = [
${stringify(app)}
];

export const GAME_GUIDE_SUMMARIES = [
${stringify(game)}
];

export const ALL_GUIDE_SUMMARIES = [...APP_GUIDE_SUMMARIES, ...GAME_GUIDE_SUMMARIES];

// Same lookup shape as index.js's getGuideBySlug, but over the light
// summaries - enough for a related-guides link or a "guide exists" check
// without importing the guide's own module.
export function getGuideSummaryBySlug(slug) {

    return ALL_GUIDE_SUMMARIES.find(guide => guide.slug === slug) ?? null;

}

// Mirror of index.js's getGameGuideForSlug - "is there a real game guide
// for this game's slug?" - for game-guide-notice.js.
export function getGameGuideSummaryForSlug(gameSlug) {

    return GAME_GUIDE_SUMMARIES.find(guide => guide.gameSlug === gameSlug) ?? null;

}
`;

}

// Run directly (not imported) -> (re)write the committed manifest.
if (import.meta.url === pathToFileURL(process.argv[1]).href) {

    const data = await buildManifestData();
    await writeFile(MANIFEST_PATH, renderManifest(data), "utf8");
    console.log(`Wrote ${MANIFEST_PATH}: ${data.app.length} app + ${data.game.length} game guides.`);

}
